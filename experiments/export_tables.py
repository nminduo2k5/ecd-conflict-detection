"""Result tables for the paper, generated straight from results/*.json (same source as numbers.tex).

    python experiments/export_tables.py [out_dir]     # -> ../ecd_latex/tab_rq1.tex, tab_rq2.tex, tab_rq4.tex
                                                       #    (or <ECD_RESULTS_DIR>/paper_tables/ when that is set)
Each file is a complete LaTeX table environment (booktabs) with caption and label.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
_env = os.environ.get("ECD_RESULTS_DIR")                     # same override as experiments/common.py
RES = (Path(_env) if Path(_env).is_absolute() else ROOT / _env) if _env else ROOT / "results"
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else (RES / "paper_tables" if _env else ROOT.parent / "ecd_latex")
OUT.mkdir(parents=True, exist_ok=True)


def load(name):
    p = RES / f"{name}.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}


def I(v):                       # integer with thin-space thousands separator
    return f"{int(round(v)):,}".replace(",", r"\,")


def F(v, nd):
    return "--" if v is None else f"{v:.{nd}f}"


def P(v, nd=1):
    return "--" if v is None else f"{100 * v:.{nd}f}"


def write(name: str, body: str):
    (OUT / f"{name}.tex").write_text("% auto-generated by experiments/export_tables.py -- do not edit\n" + body,
                                     encoding="utf-8")


# ---- RQ1: AUC per method and policy ------------------------------------------------------------
def tab_rq1():
    rq1 = load("rq1_embedding")
    rows = [("data/processed/synthetic_1k", r"synthetic\_1k"), ("data/processed/hetero_1k_h50", r"hetero\_1k\_h50"),
            ("data/processed/real/aws_managed_300", "AWS managed 300"), ("data/processed/real/xacml_gpms", "gpms"),
            ("data/processed/real/xacml_pluto", "pluto")]
    meths = ["sbert", "hash", "hash+ontology", "gnn_untrained", "gnn_contrastive"]
    lines = [r"\begin{table}[t]", r"\centering\footnotesize\setlength{\tabcolsep}{5pt}",
             r"\caption{RQ1 --- AUC of the embedding distance against the Z3 overlap label on the held-out test pairs "
             r"(best per policy in bold; hash+ont.\ is undefined for the real policies, which have no ontology; "
             r"GNN untr.: untrained, GNN: contrastively trained, ours).}",
             r"\label{tab:rq1}", r"\begin{tabular}{lrccccc}", r"\toprule",
             r"policy & test pairs & SBERT & hash & hash+ont. & GNN untr. & GNN \\", r"\midrule"]
    for ds, lab in rows:
        r = rq1.get(ds) or {}
        vals = [(r.get(m) or {}).get("auc") if isinstance(r.get(m), dict) else None for m in meths]
        vals = [None if (v is not None and v != v) else v for v in vals]
        best = max((v for v in vals if v is not None), default=None)
        cells = []
        for v in vals:
            if v is None:
                cells.append("--")
            else:
                s = F(v, 3)
                cells.append(rf"\textbf{{{s}}}" if (best is not None and best > 0 and abs(v - best) < 5e-4) else s)
        lines.append(f"{lab} & {I(r.get('n_test', 0))} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    write("tab_rq1", "\n".join(lines) + "\n")


# ---- RQ2: variants on synthetic_1k and complex_1k ------------------------------------------------
def tab_rq2():
    a, c = load("rq2_pruning"), load("rq2_complex")
    variants = [("no_tierA", r"full SMT (no Tier~A)"), ("tierA_only", r"Tier~A, exact (any order)"),
                ("approx_hash_k10", r"Tier~A + hash, top-10"), ("approx_gnn_k10", r"Tier~A + GNN, top-10"),
                ("approx_gnn_k25", r"Tier~A + GNN, top-25"), ("approx_gnn_k50", r"Tier~A + GNN, top-50")]
    idx = [("exact_index", r"literal index$^\dagger$"), ("exact_index+ont", r"index + ontology$^\dagger$")]

    def cells(d, k):
        v = d.get(k) or {}
        if "recall_on_candidates" in v:
            return f"{I(v['candidates'])} & {P(v['recall_on_candidates'])} & --"
        t = (v.get("time_ms") or {}).get("select+verify")
        return f"{I(v['verified'])} & {P(v['recall'])} & {F(t / 1000 if t is not None else None, 1)}"

    lines = [r"\begin{table}[t]", r"\centering\footnotesize\setlength{\tabcolsep}{4pt}",
             rf"\caption{{RQ2 --- full check of \texttt{{synthetic\_1k}} ({I(a['no_tierA']['pairs_total'])} pairs, {I(a['n_truth'])} "
             rf"true conflicts) and \texttt{{complex\_1k}} ({I(c['n_truth'])} conflicts): pairs sent to the solver, recall (\%) "
             r"against the exhaustive ground truth, time (s) for selection plus verification; $^\dagger$candidates and their recall.}",
             r"\label{tab:rq2}", r"\begin{tabular}{lrrrrrr}", r"\toprule",
             r" & \multicolumn{3}{c}{\texttt{synthetic\_1k}} & \multicolumn{3}{c}{\texttt{complex\_1k}} \\",
             r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}",
             r"variant & to Z3 & recall & time & to Z3 & recall & time \\", r"\midrule"]
    for k, lab in variants:
        lines.append(f"{lab} & {cells(a, k)} & {cells(c, k)} \\\\")
    lines.append(r"\midrule")
    for k, lab in idx:
        lines.append(f"{lab} & {cells(a, k)} & {cells(c, k)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    write("tab_rq2", "\n".join(lines) + "\n")


# ---- RQ4: cost of one change versus policy size ------------------------------------------------
def tab_rq4():
    rq4 = load("rq4_scalability")
    sizes = sorted(int(k) for k in rq4)
    rep = rq4[str(sizes[0])].get("repeats") if sizes else None
    nd = rq4[str(sizes[0])].get("n_deltas") if sizes else None

    def ms(v, key):
        d = v.get(key) or {}
        return rf"{F(d.get('mean'), 0)}\,$\pm$\,{F(d.get('std'), 0)}"

    lines = [r"\begin{table}[t]", r"\centering\footnotesize\setlength{\tabcolsep}{5pt}",
             rf"\caption{{RQ4 --- ms per change (mean $\pm$ sd, {rep} seeds $\times$ {nd} changes, hash embedding) in exact and "
             r"approximate ($k{=}50$) mode, pairs verified per change in exact mode, Tier~A selection time (ms) per change; $p$ (paired "
             r"Wilcoxon) and $\hat{A}_{12}$ compare approximate with exact.}",
             r"\label{tab:rq4}", r"\begin{tabular}{rrrrrcc}", r"\toprule",
             r"rules & exact & approximate & pairs/$\Delta$ & Tier~A & $p$ & $\hat{A}_{12}$ \\",
             r"\midrule"]
    for n in sizes:
        v = rq4[str(n)]
        p = v.get("p")
        ps = "--" if p is None else (r"$<$0.0001" if p < 1e-4 else F(p, 4))
        lines.append(f"{I(n)} & {ms(v, 'exact_ms_per_delta')} & {ms(v, 'approx_ms_per_delta')} & "
                     f"{F((v.get('exact_verified_per_delta') or {}).get('mean'), 0)} & "
                     f"{F((v.get('tierA_select_ms_per_delta') or {}).get('mean'), 0)} & {ps} & {F(v.get('A12'), 2)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    write("tab_rq4", "\n".join(lines) + "\n")


if __name__ == "__main__":
    tab_rq1()
    tab_rq2()
    tab_rq4()
    print("wrote", ", ".join(str(OUT / f"tab_rq{i}.tex") for i in (1, 2, 4)))
