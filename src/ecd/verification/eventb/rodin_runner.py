"""Drive Rodin headlessly to discharge POs (optional, slow path).

Pipeline
  1. `EventBLedger` writes `PolicyCtx_v<N>.buc` (Rodin XML) for every version.
  2. `RodinRunner.prepare(ctx_dir, project)` copies them into a Rodin project
     folder inside the workspace, with a `.project` file (Rodin nature +
     builder) and an Ant `build.xml`.
  3. `RodinRunner.build(project)` runs the Eclipse Ant runner inside Rodin:

        rodin -nosplash -consoleLog -application org.eclipse.ant.core.antRunner
              -data <workspace> -buildfile <workspace>/<project>/build.xml

     The build file refreshes the project and triggers a full build, i.e. the
     static checker, the PO generator and the auto-prover.  With the *SMT
     Solvers* plugin installed and enabled in the auto-tactic profile
     (Preferences ▸ Event-B ▸ Sequent Prover ▸ Auto/Post tactic ▸ add
     "SMT Solvers" to the profile), every `thm_*` PO is sent to Z3/CVC4/veriT.
  4. `RodinRunner.status(project)` parses the proof-status files (`*.bps`) and
     PO files (`*.bpo`) Rodin wrote: a PO with confidence 1000 is discharged,
     anything else is an undischarged theorem = conflict candidate.

Headless import caveat: Eclipse does not auto-import a project folder that is
merely placed in the workspace directory.  The first time, import the project
once in the Rodin UI (File ▸ Import ▸ Existing Projects into Workspace) or
start Rodin with the same `-data` workspace and the project folder present;
every later version (`PolicyCtx_v<N+1>.buc`) is then picked up by the headless
build without touching the UI.

If Rodin is not installed, the pipeline's verdicts already come from Z3 on the
*same* theorems (`app_a ∩ app_b = ∅` ⇔ UNSAT(⟦a⟧ ∧ ⟦b⟧)); the Event-B files
are still produced so the certified PO ledger can be replayed later.
"""
from __future__ import annotations

import re
import shutil
import subprocess
from dataclasses import dataclass, field
from pathlib import Path
from xml.etree import ElementTree as ET

PROJECT_XML = """<?xml version="1.0" encoding="UTF-8"?>
<projectDescription>
	<name>{name}</name>
	<comment>Generated by ecd (embedding-guided incremental conflict detection)</comment>
	<projects></projects>
	<buildSpec>
		<buildCommand>
			<name>org.rodinp.core.rodinbuilder</name>
			<arguments></arguments>
		</buildCommand>
	</buildSpec>
	<natures>
		<nature>org.rodinp.core.rodinnature</nature>
	</natures>
</projectDescription>
"""

BUILD_XML = """<?xml version="1.0" encoding="UTF-8"?>
<project name="{name}" default="build">
	<target name="build">
		<eclipse.refreshLocal resource="{name}" depth="infinite"/>
		<eclipse.incrementalBuild project="{name}" kind="full"/>
	</target>
</project>
"""


@dataclass
class RodinResult:
    discharged: int = 0
    undischarged: list[str] = field(default_factory=list)
    po_per_file: dict[str, int] = field(default_factory=dict)
    log: str = ""

    @property
    def total(self) -> int:
        return self.discharged + len(self.undischarged)


class RodinRunner:
    def __init__(self, rodin_path: str | None = None, workspace: str | Path = "results/rodin_ws"):
        self.rodin_path = rodin_path or shutil.which("rodin") or shutil.which("rodin.exe")
        self.workspace = Path(workspace)

    def available(self) -> bool:
        return bool(self.rodin_path) and Path(self.rodin_path).exists()

    # ----- project layout ----------------------------------------------------
    def prepare(self, ctx_dir: str | Path, project: str = "ECD") -> Path:
        """Create <workspace>/<project>/ with every .buc of ctx_dir, .project and build.xml."""
        proj = self.workspace / project
        proj.mkdir(parents=True, exist_ok=True)
        for f in sorted(Path(ctx_dir).glob("*.buc")):
            shutil.copy(f, proj / f.name)
        (proj / ".project").write_text(PROJECT_XML.format(name=project), encoding="utf-8")
        (proj / "build.xml").write_text(BUILD_XML.format(name=project), encoding="utf-8")
        return proj

    # ----- build -------------------------------------------------------------
    def build(self, project: str = "ECD", timeout: int = 3600) -> RodinResult:
        if not self.available():
            raise RuntimeError("Rodin not found; set eventb.rodin_path in configs/default.yaml")
        proj = self.workspace / project
        cmd = [self.rodin_path, "-nosplash", "-consoleLog",
               "-application", "org.eclipse.ant.core.antRunner",
               "-data", str(self.workspace.resolve()),
               "-buildfile", str((proj / "build.xml").resolve())]
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
        res = self.status(project)
        res.log = proc.stdout + proc.stderr
        return res

    # ----- status parsing ----------------------------------------------------
    def status(self, project: str = "ECD") -> RodinResult:
        proj = self.workspace / project
        res = RodinResult()
        for bpo in sorted(proj.glob("*.bpo")):
            try:
                root = ET.parse(bpo).getroot()
                res.po_per_file[bpo.stem] = sum(1 for e in root.iter() if e.tag.endswith("poSequent"))
            except ET.ParseError:
                continue
        for bps in sorted(proj.glob("*.bps")):
            try:
                root = ET.parse(bps).getroot()
            except ET.ParseError:
                continue
            for e in root.iter():
                if not e.tag.endswith("psStatus"):
                    continue
                name = e.get("name", "")
                conf = int(e.get("org.eventb.core.confidence", "0"))
                broken = e.get("org.eventb.core.psBroken", "false") == "true"
                if conf >= 1000 and not broken:
                    res.discharged += 1
                elif name.startswith("thm_") or re.match(r".*thm_.*/THM", name):
                    res.undischarged.append(f"{bps.stem}:{name}")
                else:
                    res.undischarged.append(f"{bps.stem}:{name}")
        return res
